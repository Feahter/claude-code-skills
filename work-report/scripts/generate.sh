#!/bin/bash
# 工作报告主流程：采集素材 → headless claude 归纳 → 落草稿 + 系统通知 → 可选自动发送。
# 只读本地仓库，只写草稿文件与日志；对外发布只发生在 send.sh，且仅当 AUTOSEND=1。
#
# 用法：generate.sh [daily|weekly]
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PERIOD="${1:-${WORK_REPORT_PERIOD:-daily}}"

case "$PERIOD" in
  daily)
    DEFAULT_REPORT_DIR="$HOME/.claude/reports/daily"
    KIND_LABEL="日报"
    ;;
  weekly)
    DEFAULT_REPORT_DIR="$HOME/.claude/reports/weekly"
    KIND_LABEL="周报"
    ;;
  *) echo "generate.sh: 未知周期 '$PERIOD'（只接受 daily / weekly）" >&2; exit 2 ;;
esac

REPORT_DIR="${WORK_REPORT_DIR:-$DEFAULT_REPORT_DIR}"
LOG_DIR="$HOME/.claude/logs"
LOG="$LOG_DIR/work-report.log"
TODAY="$(date +%Y-%m-%d)"
DRAFT="$REPORT_DIR/$TODAY.md"

# claude 归纳的双熔断：超时（秒）与模型。
# 周报素材是日报的数倍，给更长的超时：2026-09-15 实测 2 天素材（21 KB）归纳耗时 259 秒。
# 2026-09-18 五天素材 63 KB 撞破 600 秒超时回退成原始素材，且此后周报模版改成
# 「主线段 + 不限条数明细」，输出比原来长一倍，所以放到 900 秒。
if [ "$PERIOD" = "weekly" ]; then
  CLAUDE_TIMEOUT="${WORK_REPORT_TIMEOUT:-900}"
else
  # 180 秒偏紧：2026-09-14 定时任务超时过一次，2026-09-15 复测 5.8 KB 素材又超时。
  # 耗时主导因素是 commit body 的信息密度而不是素材体积（周报 21 KB 只用 259 秒，
  # 因为它的主线是已凝练的日报草稿）。日报没有硬性时间约束，放到 300 秒。
  CLAUDE_TIMEOUT="${WORK_REPORT_TIMEOUT:-300}"
fi
CLAUDE_MODEL="${WORK_REPORT_MODEL:-sonnet}"

mkdir -p "$REPORT_DIR" "$LOG_DIR"

log() { echo "[$(date '+%Y-%m-%d %H:%M:%S')] [$PERIOD] $*" >> "$LOG"; }

notify() {
  # $1=标题 $2=正文 —— macOS 通知中心
  local title="$1" body="$2"
  osascript -e "display notification \"${body//\"/\\\"}\" with title \"${title//\"/\\\"}\" sound name \"Glass\"" 2>/dev/null || true
}

# macOS 无 timeout：后台跑 + 计时 kill
run_with_timeout() {
  local secs="$1"; shift
  "$@" &
  local pid=$!
  local waited=0
  while kill -0 "$pid" 2>/dev/null; do
    sleep 2
    waited=$((waited + 2))
    if [ "$waited" -ge "$secs" ]; then
      kill -TERM "$pid" 2>/dev/null
      sleep 1
      kill -KILL "$pid" 2>/dev/null
      return 124
    fi
  done
  wait "$pid"
}

log "==== work-report start ($TODAY) ===="

# 1. 采集素材
MATERIAL="$(bash "$SCRIPT_DIR/collect.sh" "$PERIOD" 2>>"$LOG")"
COLLECT_RC=$?

if [ "$COLLECT_RC" -eq 10 ] || [ -z "$MATERIAL" ]; then
  log "窗口内无本地仓库改动，跳过。"
  exit 0
fi

log "采集完成，素材字节数: ${#MATERIAL}"

# 2. 归纳 prompt
#
# 表达规范两个周期完全一致，抽成单一事实源：口径只写一处，改日报的写法周报自动跟上。
# 各周期专属的是模版、条数上限、状态词表与合并粒度。
COMMON_STYLE="$(cat <<'STYLE_EOF'
## 表达

- 只写做了什么和结果，不写怎么做的和为什么。素材里的根因、机制、实现路径、判据、取舍理由一律不进报告——主管要知道这件事做完了没有，不需要知道是靠加闸门还是改计数实现的。
- 判断一条够不够凝练：把它读给不了解这个模块的人听，对方能听懂做了什么就够了，听不懂细节不用补。
- 用大白话写，像跟同事当面说清楚干了什么，不是写汇报材料。
- 动词要具体：修了、删了、补了、拆了、跑完、接上、换成。不用「处理」「优化」「完善」「梳理」「厘清」「收敛」「定性」「赋能」这类看不出做了什么的词。
- 语序固定为「功能模块：改动内容」，模块在前、改动在后，中间用中文冒号。先让人看到是哪块业务或哪个环节，再看动了什么。
- 模块名取业务或环节的短名，4 到 8 字，如「Arc 链余额显示」「策略页测试」「CI 报告」「pre-push 检查」「E2E 反模式闸门」。分组时不要拿仓库名当模块名，那一层已由组名承担。
- 模块名不是分类标签：不写【重构】【BUG】【测试体系】这类归类词，也不给模块名加方括号，方括号只留给句末状态。
- 模块前缀是用来定位的，不是用来压缩信息的。改动实际覆盖的范围——哪些角色、哪几个页面、哪几条链、哪几批用例——属于「做了什么」，必须留在句子里。范围塞不进模块名就写进改动内容，宁可模块名短一点，也不要把范围丢掉。
  反例：素材是「Arc 持有者/交易者余额按 native token 精度换算」，写成`Arc 链余额显示：修复余额被放大 1e12 倍的精度错误`就错了两处——丢了持有者和交易者这个范围，又把根因倍数写了进来。应写`Arc 链余额显示：修了持有者和交易者的精度错误`。
- 冒号两侧不重复用词。模块名里出现过的词，改动内容里不再说一遍，那点字数留给范围和结果。
  反例：`循环依赖闸门：加了循环依赖增量软门禁`、`E2E 反模式闸门：新增基线闸门锁定现有用例反模式`。
  应写：`循环依赖闸门：加了增量软门禁`、`E2E 反模式闸门：新增基线锁定现有用例`。
- 不用斜杠串联并列项，不用箭头代替叙述，能说「和」「从…到…」就直接说。
- 不写文件名、变量名、符号名、BUILD_ID、正则。
- 中文与英文、数字之间加一个空格，如「覆盖率 52%」「搭好 test-go 入口」。
- 不给自己的工作加评价性形容词，如「高效」「全面」「显著」「系统性」。
- 状态只由句末的方括号标注承担，句子里不要再写「已合并」「已跟版」「还没合并」「还在改」「已上线」这类话，说两遍是废字。
- 只依据素材事实，不虚构。
STYLE_EOF
)"

OUTPUT_RULE="$(cat <<'OUT_EOF'
## 输出

- 不要任何前言、解释、结尾语，只输出报告本身：日报第一行就是组名或 `1.`，周报第一行就是 `*本周主线*`。
- 结尾单独一行输出：`*发送工具* <@U0CLAUDEXXX|Claude>`
OUT_EOF
)"

if [ "$PERIOD" = "daily" ]; then
  PROMPT_HEAD="$(cat <<'HEAD_EOF'
你是帮我写每日工作日报的助手。下面是我今天在本地各仓库的 commit 素材（含提交信息、改动规模、提交正文）。

归纳成一份给主管和团队看的日报，按下面的模版和规则写，不要自创样式。

## 模版

```
<模块名>                    ← 仅跨 2 个以上仓库时输出，单一仓库不写这行
1. <功能模块>：<改动内容>【状态】
2. ...
```

## 条数与长度

- 单仓库总共 3-6 条；跨仓库时每个仓库 3-4 条、全篇不超过 8 条。素材再多也不加条数，超出就砍掉最次要的。
- 每条一行一句话，30 字以内（含模块前缀，不含句末状态标注）。超了就是话没说完就想说第二件事，先压模块名再压改动内容。
- 一条只讲一个动作。不要用逗号接第二个动作，「修了 A，又补了 B，还改了 C」要拆开或砍掉后两个。
- 同一主题的工作合并成一条，即使跨多个 commit、跨半天也要合，不逐条罗列。
- 不同主题不要因为在同一个仓库就挤进一条，各自单独一条。
- 不写子项，不分层。一条里塞不下，说明该再合并，或该砍掉次要的那部分。
- 有关键数字（覆盖率、修复条数、转绿条数）就带一个，没有不硬凑。数字只取成果规模，不取根因数据：放大多少倍、超时多少秒、阈值多少、错误码多少、常量取值，这些都是机制，一律不写。

## 分组

- 素材跨 2 个以上仓库时按仓库分组，组名单独一行（直接用仓库名，如 side-web / main-app / main-app-test），组内从 1 重新编号。
- 只有 1 个仓库时不写组名，直接从 1. 开始。

## 状态标注（每条句末必带）

素材里每条 commit 的合并状态后面已经标好「报告写【X】」，直接用那个词，不要自己从分支名推断。
下面这张表是它的口径，只在一条报告合并了好几个 commit、状态不一致时才需要自己判：

- 「已在主干」→ 【已完成】
- 「已在发版分支」→ 【今日跟版】（活已经进了本次要发的版本，在等发布，不是还在改）
- 「已在测试分支」→ 【测试中】（合到了 pre 在测，还没进发版分支，不能写跟版）
- 「仅在特性分支」，或素材显示还在改 → 【开发中】
- 素材明确提到待测试 / 待提测 → 【待提测】
- 素材明确提到在等他人（后端接口、他人合并、产品确认）→ 状态后紧跟一句卡点，如 `【开发中】等待合并`、`【开发中】等待后端提供接口`
- 长周期任务素材里有进度线索 → 直接写百分比，如 `70%`

一条日报合并了好几个 commit、它们的合并状态不一致时，取最靠后的那一档：
已完成 → 今日跟版 → 测试中 → 开发中，谁在右边取谁。判断不了就用【开发中】。
宁可保守，不要把没进主干的写成已完成，也不要把只进了 pre 的写成跟版。
只有这五个词加百分比，不要自己造新状态词。
HEAD_EOF
)"
else
  PROMPT_HEAD="$(cat <<'HEAD_EOF'
你是帮我写每周工作周报的助手。下面的素材分两段：

1. 「本周日报草稿」段——本周每天已经归纳并发出去的日报正文，已经凝练过一次、状态标注也已按合并情况判定。这段是周报的主线。
2. 「本周 commit 素材」段——本周全部 commit 的原始记录，用来补漏：某天没生成日报，或日报每天限 3-6 条时被砍掉的次要工作，只在这段里出现。

写法：以第 1 段为主线搭出周报骨架，再用第 2 段补上第 1 段完全没提到的工作。第 2 段里已经被日报覆盖过的内容不要重复成新条目。

归纳成一份给主管和团队看的周报。

周报分「本周主线」和「工作明细」两段，两段都要有，模版如下，不要自创样式。

## 模版

```
*本周主线*

<主线名>（<时间跨度>，<提交次数>）：<整周做到哪一步，留下什么。没完的说清卡在哪。>

<第二条主线>……

*工作明细*

<仓库名>                    ← 仅跨 2 个以上仓库时输出，单一仓库不写这行
1. <功能模块>：<改动内容>【状态】
2. ...
```

## 本周主线段

- 3 到 5 条。把整周的工作按「同一个目标」聚成主线：一条主线可以横跨多个仓库，也可以由分散在几天的多条工作合成。
- 每条 1 到 3 句，写整周做到哪一步、留下什么能用的东西；没做完的说清卡在哪（在等合并、在等发布、还剩哪一档）。
- 括号里带这条主线的规模：覆盖几天、多少次提交，如「整周 5 天，28 次提交」「3 天，11 次提交」。数字一律从素材的「规模统计」段取，那里按仓库和主题都算好了；一条主线跨好几个主题就把那几行的提交数相加、天数按日期并集数。不要自己从 commit 列表里数，也不要估。
- 顺序按工作量和时间跨度综合排，量大又跨天多的放最前面：先看提交次数与改动规模，再看覆盖几天，两样都小的放最后。规模统计段的两张表已经按工作量排过序，照它判断谁在前。不按仓库排，也不按日期排。
- 主线段同样不写机制、不写实现路径、不写根因。
- 主线段讲过的工作，明细段照样要列出来，两段不是二选一。

## 工作明细段

- 不设条数上限，本周所有有实质产出的工作都要列到，不因为篇幅砍掉。
- 但该合的还要合：同一件事跨几天的合成一条，同一个模块的多次提交合成一条。不设上限不等于把 commit 逐条抄下来。
- 每条一行一句话，30 字以内（含模块前缀，不含句末状态标注）。超了就是话没说完就想说第二件事，先压模块名再压改动内容。
- 一条只讲一个动作。不要用逗号接第二个动作。
- 不写子项，不分层。
- 有关键数字（覆盖率、修复条数、转绿条数、删除行数）就带一个，没有不硬凑。数字只取成果规模，不取根因数据：放大多少倍、超时多少秒、阈值多少、错误码多少、常量取值，这些都是机制，一律不写。
- 组内顺序跟着主线段走：前面主线涉及的工作先列，零散的放后面。

## 跨天合并（周报最重要的一条）

同一件事连做几天，会在好几天的日报里各出现一次，周报必须合成一条，按整周的最终结果写，不要按天罗列。

- 周一「开始拆循环依赖」+ 周三「拆完 4 处循环依赖」→ 一条：`循环依赖治理：拆解 4 处环【已完成】`
- 判断是不是同一件事看对象，不看措辞：同一个模块、同一个采集器、同一批用例的工作就是一件事。
- 合并后按整周终态写，中间过程不写。周三修了周一自己引入的问题，周报只写这件事最后成了什么样。
- 反过来，不同主题不要因为在同一个仓库、或都发生在同一天就挤进一条。

## 分组

- 素材跨 2 个以上仓库时按仓库分组，组名单独一行（直接用仓库名，如 side-web / main-app / main-app-test），组内从 1 重新编号。
- 只有 1 个仓库时不写组名，直接从 1. 开始。
- 分组顺序照素材里仓库出现的先后写，采集脚本已按工作量排好，不要自己重排，也不要照抄日报里的组顺序。

## 状态标注（每条句末必带）

素材里每条 commit 的合并状态后面已经标好周报该写的「报告写【X】」，直接用那个词。
日报草稿段里的状态标注是日报口径，【今日跟版】要换成【跟版中】。下表是完整口径：

- 「已在主干」，或日报写着【已完成】→ 【已完成】
- 「已在发版分支」，或日报写着【今日跟版】→ 【跟版中】（活已经进了要发的版本，在等发布，不是还在改）
- 「已在测试分支」，或日报写着【测试中】→ 【测试中】（合到了 pre 在测，还没进发版分支）
- 「仅在特性分支」，或日报写着【开发中】→ 【开发中】
- 日报写着【待提测】，或素材明确提到待测试 → 【待提测】
- 素材明确提到在等他人（后端接口、他人合并、产品确认）→ 状态后紧跟一句卡点，如 `【开发中】等待合并`
- 长周期任务素材里有进度线索 → 直接写百分比，如 `70%`

不要在周报里写【今日跟版】——那是日报的词，周报跨整周，一律写【跟版中】。

一条周报合并了跨几天的工作、状态不一致时，取最靠后的那一档：
已完成 → 跟版中 → 测试中 → 开发中，谁在右边取谁。一件事周一在开发、周五已进主干，写【已完成】。
判断不了就用【开发中】。宁可保守，不要把没进主干的写成已完成，也不要把只进了 pre 的写成跟版中。
只有这五个词加百分比，不要自己造新状态词。
HEAD_EOF
)"
fi

PROMPT="$(printf '%s\n\n%s\n\n%s\n\n素材如下：' "$PROMPT_HEAD" "$COMMON_STYLE" "$OUTPUT_RULE")"

OUT_TMP="$(mktemp)"
# 归纳是纯文本进、纯文本出，不需要工具、MCP 和 skill。不收窄时会继承用户 settings 的
# effortLevel（当前 xhigh）和整套 MCP、skill 清单：2026-09-23 同一份 6 KB 素材实测，
# 不带这些参数 911 秒仍被 900 秒熔断杀掉，带上后 48 秒出稿。四项没有逐个拆开测，哪项是大头未定。
run_with_timeout "$CLAUDE_TIMEOUT" bash -c "printf '%s\n\n%s\n' \"\$1\" \"\$2\" | claude -p --model '$CLAUDE_MODEL' --effort medium --tools '' --strict-mcp-config --disable-slash-commands --no-session-persistence > '$OUT_TMP' 2>>'$LOG'" _ "$PROMPT" "$MATERIAL"
GEN_RC=$?

REPORT="$(cat "$OUT_TMP" 2>/dev/null)"
rm -f "$OUT_TMP"

if [ "$GEN_RC" -eq 124 ]; then
  log "claude 归纳超时（${CLAUDE_TIMEOUT}s），回退为原始素材草稿。"
  REPORT=""
fi

# 3. 落草稿：claude 成功用归纳结果，失败/超时回退原始素材（保证一定有产出）
{
  echo "# ${KIND_LABEL}草稿 $TODAY"
  echo ""
  if [ -n "$REPORT" ]; then
    echo "$REPORT"
  else
    echo "> ⚠️ claude 归纳失败或超时，以下为原始素材，请手动整理。"
    echo ""
    echo "$MATERIAL"
  fi
  echo ""
  echo "---"
  echo "_自动生成于 $(date '+%Y-%m-%d %H:%M:%S')，仅本地草稿，请核对后再发 Slack。_"
} > "$DRAFT"

log "草稿已写入: $DRAFT (归纳rc=$GEN_RC)"

# 3.5 草稿自检：条数、字数、状态词串没串周期、两段结构齐不齐，都是能机械判定的，
# 交给 lint-draft.py 查，人工过目时直接看注脚，不必自己数。结果写在 --- 之后，
# send.sh 发送时会连注脚一起剥掉，不会进群。
LINT="$(python3 "$SCRIPT_DIR/lint-draft.py" "$DRAFT" "$PERIOD" 2>>"$LOG")"
if [ -n "$LINT" ]; then
  { echo ""; printf '%s\n' "$LINT"; } >> "$DRAFT"
  log "自检: $(printf '%s' "$LINT" | head -1)"
fi

# 4. 系统通知
if [ -n "$REPORT" ]; then
  notify "📋 今日${KIND_LABEL}草稿已生成" "$TODAY · $(printf '%s' "$LINT" | head -1) · 核对后发 Slack"
else
  notify "⚠️ ${KIND_LABEL}草稿（归纳失败，含原始素材）" "$TODAY · 请手动整理 $DRAFT"
fi

